#!/usr/bin/env python3
"""docs/writfold/laws.md: the laws of the calculus, generated (#206).

One page a reviewer reads to see every law, its Lean statement, the
kernels shown to implement it and what would catch a broken definition,
with the coverage of the translation. Generated from proofs/Calculus,
proofs/laws.toml, proofs/mutants.py and proofs/unlinked.txt; the quality
gate refuses a page that differs from a fresh one, and a calculus theorem
without a doc comment (the proofs gate's image holds no docs/, so it runs
law_coverage.py only).

    python3 proofs/laws_page.py           check the committed page
    python3 proofs/laws_page.py --write   regenerate it
"""
from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAGE = HERE.parent / "docs" / "writfold" / "laws.md"
NAMESPACE = re.compile(r"^namespace\s+(?P<name>\S+)")

SECTIONS = {
    "Word.lean": "Words, decisions and admission",
    "Account.lean": "The accounted universe (law U)",
    "Evidence.lean": "Evidence: classes, policy, one record decides",
    "Site.lean": "Sites and postures (law S)",
    "Referent.lean": "Referents and the asset boundary (laws R and A)",
}


def laws(path: Path) -> tuple[list[tuple[str, str, str]], list[str]]:
    """(name, doc, statement) of each theorem in a calculus file, and the
    names of theorems with no doc comment."""
    out, undocumented = [], []
    stack: list[str] = []
    lines = path.read_text().splitlines()
    for index, line in enumerate(lines):
        if match := NAMESPACE.match(line):
            stack.append(match.group("name"))
        elif line.startswith("end ") and stack:
            stack.pop()
        elif line.startswith("theorem "):
            name = ".".join([*stack, line.split()[1]])
            doc = doc_before(lines, index)
            if doc is None:
                undocumented.append(name)
                continue
            text = " ".join(l.strip() for l in lines[index:index + 12])
            statement = text[len("theorem "):text.find(":=")].strip()
            out.append((name, doc, " ".join(statement.split())))
    return out, undocumented


def doc_before(lines: list[str], index: int) -> str | None:
    end = index - 1
    if end < 0 or not lines[end].rstrip().endswith("-/"):
        return None
    start = end
    while start >= 0 and "/--" not in lines[start]:
        start -= 1
    if start < 0:
        return None
    text = " ".join(l.strip() for l in lines[start:end + 1])
    return " ".join(text.replace("/--", "").replace("-/", "").split())


def page() -> tuple[str, list[str]]:
    sys.path.insert(0, str(HERE))
    import law_coverage  # noqa: E402 (the same directory)
    import mutants  # noqa: E402
    register = tomllib.loads((HERE / "laws.toml").read_text())
    links = register.get("link", [])
    breakers: dict[str, list[str]] = {}
    for m in mutants.CORE_MUTANTS:
        for name in m.fails:
            breakers.setdefault(name, []).append(m.name)
    errors, coverage = law_coverage.check(HERE)
    out = [
        "# The laws of the calculus",
        "",
        "Generated by `proofs/laws_page.py` from `proofs/Calculus/`, `proofs/laws.toml`,",
        "`proofs/mutants.py` and `proofs/unlinked.txt`; do not edit by hand. The quality",
        "gate refuses this page when it differs from a fresh one.",
        "",
        "Each law is a theorem in plain Lean ([RFC](../rfcs/2026-11-27-calculus-in-lean.md)),",
        "independent of the Rust. A kernel is *linked* when a theorem shows the shipped",
        "Rust, through its Aeneas translation, implements the operation a law is about;",
        "every law of that operation then holds of the kernel. A law is *caught* by the",
        "core mutants that break it, or *derived* from the laws it follows from.",
        "",
        "**Rule** (AGENTS.md): new or changed decision logic states the law it obeys in",
        "`proofs/Calculus` with a doc comment, links its kernel in `proofs/laws.toml`, and",
        "regenerates this page in the same commit.",
        "",
        "## Coverage",
        "",
        f"`{coverage}`",
        "",
        "*judged*: translated functions linked to a law; *declared_out*: functions the",
        "calculus is not about, with a reason; *remainder*: the backlog in",
        "`proofs/unlinked.txt`, which only shrinks.",
        "",
    ]
    problems = list(errors)
    for file, title in SECTIONS.items():
        found, undocumented = laws(HERE / "Calculus" / file)
        problems += [f"{name}: a calculus theorem without a doc comment" for name in undocumented]
        out += [f"## {title}", "", f"From `proofs/Calculus/{file}`.", ""]
        for name, doc, statement in found:
            implemented = sorted(f"`{l['function']}`" for l in links if name in l.get("laws", []))
            caught = breakers.get(name)
            derived = mutants.DERIVED.get(name)
            out += [f"### `{name}`", "", doc, "", "```lean", statement, "```", ""]
            if implemented:
                out.append(f"- Implemented by: {', '.join(implemented)}")
            if caught:
                out.append(f"- Caught by: {', '.join(f'`{m}`' for m in caught)}")
            elif derived:
                out.append(f"- Derived: {derived}")
            out.append("")
    out += ["## Links", "", "| Function | Implements | Theorem |", "|---|---|---|"]
    for l in sorted(links, key=lambda l: l["function"]):
        out.append(f"| `{l['function']}` | `{l['implements']}` | `{l['theorem']}` |")
    out += ["", "## Words", "", "| Rust type | Calculus word | Abstraction |", "|---|---|---|"]
    for w in sorted(register.get("word", []), key=lambda w: w["type"]):
        out.append(f"| `{w['type']}` | `{w['core']}` | `{w['abstraction']}` (onto: `{w['onto']}`) |")
    if register.get("out"):
        out += ["", "## Declared out", "", "| Function | Why |", "|---|---|"]
        for o in sorted(register["out"], key=lambda o: o["function"]):
            out.append(f"| `{o['function']}` | {o['why']} |")
    return "\n".join(out) + "\n", problems


def main() -> int:
    text, problems = page()
    for problem in problems:
        print(f"laws_page: {problem}")
    if "--write" in sys.argv[1:]:
        PAGE.write_text(text)
        print(f"laws_page: wrote {PAGE.relative_to(HERE.parent)}")
    elif not PAGE.is_file() or PAGE.read_text() != text:
        print("laws_page: docs/writfold/laws.md differs from a fresh page; run python3 proofs/laws_page.py --write")
        return 1
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
