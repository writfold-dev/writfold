"""Generate compatibility data only, never qualification evidence.

Run with Python 3.12 from the admitted immutable writfold-tools image, offline.
The Rust algorithms consuming these tables are handwritten, not generated.
"""
import hashlib
import json
from pathlib import Path
import re
import sys
import unicodedata

IMAGE = "writfold-tools@sha256:c854889f19c83174e69600ee28f0d4d35a0d2de1a23b3a35b1ecf4c4a88e0fc6"


def ranges(predicate):
    result = []
    first = None
    for number in range(0x110000):
        if predicate(chr(number)):
            if first is None:
                first = number
        elif first is not None:
            result.append((first, number - 1))
            first = None
    if first is not None:
        result.append((first, 0x10FFFF))
    return result


def main():
    if sys.version_info[:2] != (3, 12) or unicodedata.unidata_version != "15.0.0":
        raise RuntimeError("generation requires Python 3.12 / Unicode 15.0.0")
    predicates = {
        "WORD": lambda char: re.fullmatch(r"\w", char) is not None,
        "DECIMAL": lambda char: re.fullmatch(r"\d", char) is not None,
        "LINE_BREAK": lambda char: len(("a" + char + "b").splitlines()) == 2,
    }
    lines = ["// Generated by tools/generate_unicode.py; Python 3.12, Unicode 15.0.0."]
    for name, predicate in predicates.items():
        values = ranges(predicate)
        lines.append("#[rustfmt::skip]")
        lines.append(f"pub(super) const {name}: &[(u32, u32)] = &[")
        for index in range(0, len(values), 4):
            lines.append("    " + " ".join(f"(0x{a:X}, 0x{b:X})," for a, b in values[index:index + 4]))
        lines.append("];")
    root = Path(__file__).resolve().parent.parent
    data = ("\n".join(lines) + "\n").encode()
    (root / "src/unicode_data.rs").write_bytes(data)
    provenance = {
        "purpose": "data_generation_only_not_qualification",
        "image": IMAGE,
        "python": sys.version,
        "unicode": unicodedata.unidata_version,
        "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "output_sha256": hashlib.sha256(data).hexdigest(),
        "predicates": {"WORD": "re.fullmatch(r'\\w', char)", "DECIMAL": "re.fullmatch(r'\\d', char)", "LINE_BREAK": "len(('a'+char+'b').splitlines()) == 2"},
    }
    (root / "unicode-provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")


if __name__ == "__main__":
    main()
